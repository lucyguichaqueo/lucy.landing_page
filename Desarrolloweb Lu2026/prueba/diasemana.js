let numeroDia = Number( prompt("Ingresá un número del 1 al 7"));

switch (numeroDia) {
    case 1:
    alert("Lunes");
        break;

    case 2:
    alert("Martes");
        break;
    
    case 3:
    alert("Miercoles");
        break;
    
    case 4:
    alert("Jueves");
        break

    case 5:
    alert("Viernes");
        break; 

    case 5:
    alert("Sabado");
        break;

    case 6:
    alert("Domingo0");
        break;
        
    default:
        break;
}